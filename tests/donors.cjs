const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const moduleScope = { exports: {} };
new Function('exports', ts.transpileModule(fs.readFileSync('lib/donors.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(moduleScope.exports);
const { donorSummary, notificationChoices, planProgress } = moduleScope.exports;
const payment = (amount, status, extra = {}) => ({ donor_id: 'a', amount_sek: amount, status, method: 'swish', ...extra });
const totals = summary => [summary.pledged, summary.paid, summary.remaining];
assert.deepEqual(totals(donorSummary('a', [payment(100, 'confirmed'), payment(200, 'pending'), payment(300, 'rejected'), payment(999, 'confirmed', { donor_id: 'b' })], [])), [300, 100, 200]);
const plan = { id: 'plan', donor_id: 'a', total_amount_sek: 1200, status: 'active', method: 'bank_transfer', installments_paid: 12 };
const installment = payment(200, 'confirmed', { donor_id: null, payment_plan_id: 'plan' });
assert.deepEqual(totals(donorSummary('a', [installment, payment(200, 'pending', { payment_plan_id: 'plan' })], [plan])), [1200, 200, 1000]);
assert.deepEqual(totals(donorSummary('a', [installment], [{ ...plan, status: 'cancelled' }])), [200, 200, 0]);
assert.deepEqual(totals(donorSummary('a', [payment(1400, 'confirmed', { payment_plan_id: 'plan' }), payment(100, 'pending')], [plan])), [1500, 1400, 100]);
assert.equal(notificationChoices({ comm_sms: true, comm_whatsapp: true }), 'SMS, WhatsApp');
assert.equal(notificationChoices({ comm_sms: true, comm_opt_out: true }), 'Inga aviseringar');
console.log('Donor totals and notification choices passed.');
const monthlyPlan = { ...plan, months: 6, amount_per_month_sek: 200 };
assert.equal(planProgress(monthlyPlan, []), '0|6');
assert.equal(planProgress(monthlyPlan, [installment]), '1|6');
assert.equal(planProgress(monthlyPlan, [payment(100, 'confirmed', { payment_plan_id: 'plan' })]), '0|6');
assert.equal(planProgress(monthlyPlan, [payment(200, 'pending', { payment_plan_id: 'plan' })]), '0|6');
assert.equal(planProgress(monthlyPlan, [payment(1400, 'confirmed', { payment_plan_id: 'plan' })]), '6|6');
console.log('Plan progress passed.');
