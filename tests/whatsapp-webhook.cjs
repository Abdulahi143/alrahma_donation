const assert = require('node:assert/strict');
const fs = require('node:fs');
const crypto = require('node:crypto');
const ts = require('typescript');
const scope = {};
new Function('exports', 'require', ts.transpileModule(fs.readFileSync('lib/whatsapp-webhook.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(scope, require);
const { validWhatsAppSignature, deliveryEvents } = scope;
const body = JSON.stringify({ object: 'whatsapp_business_account', entry: [{ changes: [{ field: 'messages', value: { metadata: { phone_number_id: 'test-phone' }, statuses: [{ id: 'message-1', status: 'delivered', timestamp: '1700000000', recipient_id: 'private-phone' }] } }] }] });
const signature = `sha256=${crypto.createHmac('sha256', 'test-secret').update(body).digest('hex')}`;
assert.equal(validWhatsAppSignature(body, signature, 'test-secret'), true);
assert.equal(validWhatsAppSignature(body + ' ', signature, 'test-secret'), false);
assert.equal(validWhatsAppSignature(body, 'sha256=invalid', 'test-secret'), false);
assert.equal(validWhatsAppSignature(body, signature, ''), false);
const events = deliveryEvents(JSON.parse(body), 'test-phone');
assert.equal(events.length, 1);
assert.equal(events[0].status, 'delivered');
assert.equal('recipient_id' in events[0], false);
assert.deepEqual(deliveryEvents(JSON.parse(body), 'other-phone'), []);
assert.deepEqual(deliveryEvents({ object: 'page', entry: [] }, 'test-phone'), []);
assert.deepEqual(deliveryEvents(null, 'test-phone'), []);
console.log('Webhook signature, sender filtering, and delivery data checks passed.');
